/**
 * Размеры пачки кадров для ONNX — те же значения, что `BATCH_SIZES` в движке
 * (server/ts/upscale.ts). Список держим и здесь, и на сервере в одном виде:
 * расхождение поймает тест.
 *
 * `BATCH_AUTO` (0) — «Авто»: движок сам считает, сколько кадров влезает в
 * свободную видеопамять, и берёт максимум без риска нехватки памяти.
 * Большие ручные пачки (128) на крупных кадрах движок тоже урезает по памяти.
 */
export const BATCH_SIZES = [1, 2, 4, 8, 16, 32, 64, 128] as const;

/** Значение «Авто» для `batchFrames`. */
export const BATCH_AUTO = 0;

/** Что показывать в списке: «Авто» + ручные размеры. */
export const BATCH_CHOICES = [BATCH_AUTO, ...BATCH_SIZES] as const;

/**
 * Пачка ТАЙЛОВ интерполятора (вторая настройка пачки): тайлы интерполятора мелкие
 * (обычно 512×512), поэтому список короче — 32 и 128 дали бы сотни мегабайт
 * буферов без выигрыша в скорости.
 */
export const INTERP_BATCH_CHOICES = [BATCH_AUTO, 1, 2, 4, 8, 16] as const;
